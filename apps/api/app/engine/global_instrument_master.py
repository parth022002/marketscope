@dataclass
class CompanyLegalEntity:
    """
    Authoritative corporate entity holding issuer-level identifiers and fundamentals.
    A single company can have multiple exchange listings across domestic and global venues.
    """
    company_id: str
    legal_name: str
    display_name: str
    country: str
    country_code: str
    sector: str
    industry: str
    description: str
    website: str
    incorporation_country: str = "IN"
    listings: list[str] = field(default_factory=list)  # List of instrument_ids


@dataclass
class GlobalInstrument:
    """
    Authoritative exchange-specific financial instrument / listing.
    Never identified solely by ticker symbol — resolves via (exchange, symbol, instrument_id).
    """
    instrument_id: str
    company_id: str
    company_legal_name: str
    display_name: str
    symbol: str
    previous_symbol: str | None
    isin: str | None
    cusip: str | None
    figi: str | None
    exchange_id: str
    exchange_name: str
    country: str
    country_code: str
    currency: str
    security_type: str        # COMMON_STOCK, DVR_EQUITY, PREFERRED_STOCK, ADR, GDR, ETF, REIT, INDEX
    industry: str
    sector: str
    market_cap_category: str  # LARGE_CAP, MID_CAP, SMALL_CAP, MICRO_CAP
    market_cap: float         # In Crore INR for IN, Millions USD/Local for Global
    market_cap_display: str
    current_price: float
    change_pct: float
    pe_ratio: float | None
    pb_ratio: float | None
    roe: float | None
    dividend_yield: float | None
    volume_24h: int
    listing_status: str       # ACTIVE, SUSPENDED, DELISTED, NEWLY_LISTED
    trading_status: str       # TRADING, HALTED, AUCTION
    listing_date: str
    delisting_date: str | None
    market_data_provider: str
    financial_data_provider: str
    quote_available: bool
    historical_data_available: bool
    financials_available: bool
    fundamentals_available: bool
    news_available: bool
    data_status: str = "LIVE_MARKET"
    created_at: str = "2026-01-01T00:00:00Z"
    last_verified_at: str = "2026-11-22T00:00:00Z"
    aliases: list[str] = field(default_factory=list)
    share_class: str = "Ordinary Shares"
    voting_rights: float = 1.0


