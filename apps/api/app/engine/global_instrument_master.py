# ─────────────────────────────────────────────────────────────────────────────
# 3. Universal Global Instrument Repository Service
# ─────────────────────────────────────────────────────────────────────────────

class GlobalInstrumentMasterService:
    """
    High-performance, in-memory indexed Global Instrument Master repository.
    Enforces exchange-specific symbol uniqueness, ISIN indexing, multi-share class resolution,
    and server-side relevance-ranked search.
    """

    def __init__(self):
        self._companies: dict[str, CompanyLegalEntity] = {}
        self._instruments: dict[str, GlobalInstrument] = {}
        self._by_isin: dict[str, GlobalInstrument] = {}
        self._by_exchange: dict[str, list[GlobalInstrument]] = {}
        self._by_symbol: dict[str, list[GlobalInstrument]] = {}
        self._by_company: dict[str, list[GlobalInstrument]] = {}

        self._load_seed_catalog()

    def _load_seed_catalog(self):
        """Loads and indexes the seed company and instrument catalogs."""
        for c in RAW_COMPANIES_DATA:
            entity = CompanyLegalEntity(
                company_id=c["company_id"],
                legal_name=c["legal_name"],
                display_name=c["display_name"],
                country=c["country"],
                country_code=c["country_code"],
                sector=c["sector"],
                industry=c["industry"],
                description=c["description"],
                website=c["website"],
                incorporation_country=c.get("incorporation_country", "IN"),
                listings=[],
            )
            self._companies[entity.company_id] = entity

        for inst in RAW_INSTRUMENTS_DATA:
            obj = GlobalInstrument(**inst)
            self.register_instrument(obj)

    def register_instrument(self, inst: GlobalInstrument) -> None:
        """Registers and indexes a new or updated global instrument."""
        self._instruments[inst.instrument_id] = inst

        # Index by ISIN
        if inst.isin:
            self._by_isin[inst.isin.upper()] = inst

        # Index by Exchange
        if inst.exchange_id not in self._by_exchange:
            self._by_exchange[inst.exchange_id] = []
        if inst not in self._by_exchange[inst.exchange_id]:
            self._by_exchange[inst.exchange_id].append(inst)

        # Index by Symbol (uppercase)
        sym_key = inst.symbol.upper()
        if sym_key not in self._by_symbol:
            self._by_symbol[sym_key] = []
        if inst not in self._by_symbol[sym_key]:
            self._by_symbol[sym_key].append(inst)

        # Index by Company
        if inst.company_id not in self._by_company:
            self._by_company[inst.company_id] = []
        if inst not in self._by_company[inst.company_id]:
            self._by_company[inst.company_id].append(inst)

        # Update company's listing references
        company = self._companies.get(inst.company_id)
        if company and inst.instrument_id not in company.listings:
            company.listings.append(inst.instrument_id)

    # ── Lookup Methods ──

    def get_instrument_by_id(self, instrument_id: str) -> GlobalInstrument | None:
        """Looks up an instrument by its canonical internal ID."""
        clean_id = instrument_id.strip().lower()
        if clean_id in self._instruments:
            return self._instruments[clean_id]

        # Check by symbol fallback if ID not found
        sym_clean = clean_id.replace("in-nse-", "").replace("us-nasdaq-", "").replace("us-nyse-", "").replace("live-", "").upper()
        matches = self._by_symbol.get(sym_clean, [])
        if matches:
            return matches[0]

        return None

    def get_instrument_by_symbol(self, symbol: str, exchange: str | None = None) -> GlobalInstrument | None:
        """Looks up an instrument by symbol, optionally scoped to an exchange."""
        clean_sym = symbol.strip().upper()
        matches = self._by_symbol.get(clean_sym, [])
        if exchange:
            ex_clean = exchange.upper().strip()
            for m in matches:
                if m.exchange_id.upper() == ex_clean:
                    return m
            return None
        return matches[0] if matches else None

    def get_company_by_id(self, company_id: str) -> CompanyLegalEntity | None:
        """Looks up a company legal entity by company_id."""
        return self._companies.get(company_id)

    def get_instruments_by_company(self, company_id: str) -> list[GlobalInstrument]:
        """Returns all cross-exchange listings for a company."""
        return self._by_company.get(company_id, [])

    def get_instrument_by_isin(self, isin: str) -> GlobalInstrument | None:
        """Looks up an instrument by official 12-character ISIN."""
        return self._by_isin.get(isin.strip().upper())

    def get_instruments_by_exchange(
        self,
        exchange_id: str,
        limit: int = 50,
        offset: int = 0,
    ) -> list[GlobalInstrument]:
        """Returns paginated instruments for a specific exchange."""
        items = self._by_exchange.get(exchange_id.upper(), [])
        return items[offset : offset + limit]

    def count_by_exchange(self, exchange_id: str) -> int:
        return len(self._by_exchange.get(exchange_id.upper(), []))

    def get_all_instruments(self) -> list[GlobalInstrument]:
        return list(self._instruments.values())

    def get_all_companies(self) -> list[CompanyLegalEntity]:
        return list(self._companies.values())

    # ── Universal Ranked Search Engine ──

    def search(
        self,
        query: str,
        exchange: str | None = None,
        country: str | None = None,
        sector: str | None = None,
        security_type: str | None = None,
        limit: int = 50,
    ) -> list[dict[str, Any]]:
        """
        Server-side ranked search across trading symbol, ISIN, company name, industry, and aliases.
        
        Ranking Tiers:
        1. Exact Trading Symbol match (Score: 100)
        2. Exact ISIN match (Score: 95)
        3. Exact Company Legal Name match (Score: 90)
        4. Symbol Prefix Match (Score: 80)
        5. Company Name Prefix Match (Score: 75)
        6. Substring in Symbol or Name (Score: 60)
        7. Substring in Sector or Industry (Score: 40)
        8. Substring in Aliases (Score: 35)
        """
        q = query.strip()
        if not q:
            return []

        q_lower = q.lower()
        q_upper = q.upper()

        scored_results: list[tuple[float, GlobalInstrument]] = []

        for inst in self._instruments.values():
            # Apply Filters First
            if exchange and inst.exchange_id.upper() != exchange.strip().upper():
                continue
            if country and inst.country_code.upper() != country.strip().upper():
                continue
            if sector and inst.sector.lower() != sector.strip().lower():
                continue
            if security_type and inst.security_type.upper() != security_type.strip().upper():
                continue

            score = 0.0

            # 1. Exact Symbol
            if inst.symbol.upper() == q_upper:
                score = 100.0
            # 2. Exact ISIN
            elif inst.isin and inst.isin.upper() == q_upper:
                score = 95.0
            # 3. Exact Company Name
            elif inst.company_legal_name.lower() == q_lower:
                score = 90.0
            # 4. Symbol Prefix
            elif inst.symbol.upper().startswith(q_upper):
                score = 80.0
            # 5. Company Name Prefix
            elif inst.company_legal_name.lower().startswith(q_lower) or inst.display_name.lower().startswith(q_lower):
                score = 75.0
            # 6. Substring in Symbol
            elif q_upper in inst.symbol.upper():
                score = 65.0
            # 7. Substring in Company Name
            elif q_lower in inst.company_legal_name.lower() or q_lower in inst.display_name.lower():
                score = 60.0
            # 8. Substring in Sector / Industry
            elif q_lower in inst.sector.lower() or q_lower in inst.industry.lower():
                score = 40.0
            # 9. Alias Match
            elif any(q_lower in a.lower() for a in inst.aliases):
                score = 50.0

            if score > 0:
                # Slight boost for large cap liquidity
                if inst.market_cap_category == "LARGE_CAP":
                    score += 1.5
                scored_results.append((score, inst))

        # Sort descending by score, then ascending by symbol
        scored_results.sort(key=lambda x: (-x[0], x[1].symbol))

        results: list[dict[str, Any]] = []
        for score, inst in scored_results[:limit]:
            # Check if this company has other listings (for disambiguation UX)
            other_listings = [
                {"exchange": other.exchange_id, "symbol": other.symbol, "id": other.instrument_id}
                for other in self._by_company.get(inst.company_id, [])
                if other.instrument_id != inst.instrument_id
            ]

            clean_q = query.strip().upper()
            if clean_q == inst.symbol.upper():
                match_reason = "EXACT_SYMBOL"
            elif inst.isin and clean_q == inst.isin.upper():
                match_reason = "EXACT_ISIN"
            elif inst.symbol.upper().startswith(clean_q):
                match_reason = "SYMBOL_PREFIX"
            elif clean_q == inst.company_legal_name.upper():
                match_reason = "COMPANY_EXACT"
            else:
                match_reason = "QUERY_MATCH"
            results.append({
                "instrument_id": inst.instrument_id,
                "company_id": inst.company_id,
                "symbol": inst.symbol,
                "company_name": inst.company_legal_name,
                "display_name": inst.display_name,
                "exchange": inst.exchange_id,
                "exchange_name": inst.exchange_name,
                "country": inst.country,
                "country_code": inst.country_code,
                "currency": inst.currency,
                "security_type": inst.security_type,
                "sector": inst.sector,
                "industry": inst.industry,
                "isin": inst.isin,
                "price": inst.current_price,
                "change_pct": inst.change_pct,
                "market_cap_display": inst.market_cap_display,
                "market_cap": inst.market_cap,
                "listing_status": inst.listing_status,
                "data_status": inst.data_status,
                "score": round(score, 1),
                "relevance_score": round(score, 1),
                "match_reason": match_reason,
                "has_multiple_listings": len(other_listings) > 0,
                "alternative_listings": other_listings,
            })

        return results

