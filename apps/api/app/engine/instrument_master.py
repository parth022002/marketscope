class UniversalInstrumentMaster:
    """Provides high-speed indexing, search, filtering, and regulatory metadata enrichment."""

    def __init__(self):
        self._by_id: dict[str, UniversalInstrument] = {}
        self._by_symbol: dict[str, UniversalInstrument] = {}
        self._all_instruments: list[UniversalInstrument] = []
        self._initialize_master()

    def _initialize_master(self):
        for raw in RAW_INSTRUMENTS_CATALOG:
            # Classify regulatory access
            classification = investment_access_engine.classify(
                asset_class=raw["asset_class"],
                exchange=raw["exchange"],
                country_code=raw["country_code"],
                isin=raw.get("isin"),
            )

            inst = UniversalInstrument(
                instrument_id=raw["id"],
                symbol=raw["symbol"],
                alt_symbols=raw.get("alt_symbols", []),
                name=raw["name"],
                asset_class=raw["asset_class"],
                instrument_type=raw.get("type", "COMMON_STOCK"),
                country=raw["country"],
                country_code=raw["country_code"],
                region=raw["region"],
                exchange=raw["exchange"],
                mic=raw.get("mic", "XNSE"),
                trading_currency=raw["currency"],
                settlement_currency=raw["currency"],
                isin=raw.get("isin"),
                bse_scrip_code=raw.get("scrip"),
                price_precision=raw.get("precision", 2),
                tick_size=raw.get("tick", 0.05),
                timezone="Asia/Kolkata" if raw["country_code"] == "IN" else "America/New_York",
                market_calendar=raw["exchange"],
                trading_status="ACTIVE",
                historical_data_available=True,
                streaming_available=True,
                data_delivery_mode=raw.get("delivery", "REALTIME_STREAM"),
                data_licensing_status=raw.get("licensing", "LICENSED_DISPLAY"),
                investment_access_status=classification.status.value,
                permitted_investment_route=classification.permitted_route,
                notes=classification.description,
            )

            self._by_id[inst.instrument_id] = inst
            self._by_symbol[inst.symbol.upper()] = inst
            for alt in inst.alt_symbols:
                self._by_symbol[alt.upper()] = inst
            self._all_instruments.append(inst)

    def get_instrument(self, instrument_id: str) -> UniversalInstrument | None:
        return self._by_id.get(instrument_id)

    def find_by_symbol(self, symbol: str, exchange: str | None = None) -> UniversalInstrument | None:
        sym_clean = symbol.upper().strip()
        inst = self._by_symbol.get(sym_clean)
        if inst and (not exchange or inst.exchange.upper() == exchange.upper()):
            return inst
        return None

    def get_by_symbol(self, symbol: str, exchange: str | None = None) -> UniversalInstrument | None:
        return self.find_by_symbol(symbol, exchange)

    def search_instruments(
        self,
        query: str = "",
        asset_class: str | None = None,
        country: str | None = None,
        region: str | None = None,
        exchange: str | None = None,
        access_status: str | None = None,
        limit: int = 50,
    ) -> list[UniversalInstrument]:
        q = query.lower().strip()
        results: list[UniversalInstrument] = []

        for inst in self._all_instruments:
            # Filter checks
            if asset_class and inst.asset_class.upper() != asset_class.upper():
                continue
            if country and inst.country.lower() != country.lower() and inst.country_code.lower() != country.lower():
                continue
            if region and inst.region.lower() != region.lower():
                continue
            if exchange and inst.exchange.upper() != exchange.upper():
                continue
            if access_status and inst.investment_access_status.upper() != access_status.upper():
                continue

            # Query match
            if q:
                matches_symbol = q in inst.symbol.lower()
                matches_name = q in inst.name.lower()
                matches_isin = bool(inst.isin and q in inst.isin.lower())
                matches_alt = any(q in alt.lower() for alt in inst.alt_symbols)
                if not (matches_symbol or matches_name or matches_isin or matches_alt):
                    continue

            results.append(inst)
            if len(results) >= limit:
                break

        return results

    def list_by_asset_class(self, asset_class: str) -> list[UniversalInstrument]:
        return [inst for inst in self._all_instruments if inst.asset_class.upper() == asset_class.upper()]

    def get_canonical_count(self) -> int:
        return len(self._all_instruments)


# Global singleton instance
universal_instrument_master = UniversalInstrumentMaster()
